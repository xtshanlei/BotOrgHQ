export function workbenchLocale(locale) {
  return /^zh(?:-|$)/i.test(locale ?? '') ? 'zh' : 'en';
}

export function translateWorkbench(locale, key, values = {}) {
  const template = workbenchLocale(locale) === 'zh' && Object.hasOwn(workbenchMessages, key) ? workbenchMessages[key] : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}

const notificationLabels = {
  '新的工作建议': 'New work suggestion',
  '任务来源引文校验通过': 'Source quotations verified',
  '任务结果待复核': 'Task result awaits review',
  '主动工作未能完成': 'Proactive work could not finish'
};

export function translateNotification(locale, title) {
  // These titles were stored in Chinese before workbench language support.
  const approvalPrefix = '需要批准 · ';
  if (title.startsWith(approvalPrefix)) {
    return translateWorkbench(locale, 'Approval required · {summary}', { summary: title.slice(approvalPrefix.length) });
  }
  return Object.hasOwn(notificationLabels, title) ? translateWorkbench(locale, notificationLabels[title]) : title;
}
