export function desktopLocale(language) {
  return /^zh(?:-|$)/i.test(language ?? '') ? 'zh' : 'en';
}

export function translateDesktop(locale, key, values = {}) {
  const template = locale === 'zh' && Object.hasOwn(desktopMessages, key) ? desktopMessages[key] : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
