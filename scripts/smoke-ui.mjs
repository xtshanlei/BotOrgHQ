import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { startEngine } from '../desktop/engine.mjs';
const { chromium } = createRequire(process.env.PLAYWRIGHT_PACKAGE_JSON ?? import.meta.url)('playwright');
const home = await mkdtemp(join(tmpdir(), 'bohq-ui-'));
const engine = startEngine(new URL('../desktop/runtime', import.meta.url).pathname, home);
let browser;
let page;
try {
  const url = await engine.ready;
  browser = await chromium.launch({ args: ['--no-sandbox'] });
  page = await browser.newPage({ viewport: { width: 1450, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url.href);
  await page.waitForTimeout(2500);
  await page.keyboard.press('Escape');
  const close = page.getByRole('button', { name: /^(Close|关闭)( dialog|对话框)?$/i });
  if (await close.first().isVisible()) await close.first().click();
  page.setDefaultTimeout(30_000);
  const shortcut = page.getByRole('button', { name: 'BotOrgHQ', exact: true });
  if (await shortcut.count()) await shortcut.first().click();
  else await page.getByText('BotOrgHQ', { exact: true }).first().click();
  await page.getByRole('button', { name: '＋ 新建公司', exact: true }).click();
  await page.getByLabel('公司名称', { exact: true }).fill('UI Research Co');
  await page.getByRole('button', { name: '创建公司', exact: true }).click();
  await page.getByRole('button', { name: '＋ 新建部门', exact: true }).click();
  await page.getByLabel('部门名称', { exact: true }).fill('Research');
  await page.getByRole('button', { name: '创建部门', exact: true }).click();
  await page.getByRole('button', { name: '任务看板', exact: true }).click();
  await page.getByRole('button', { name: '＋ 新建任务', exact: true }).click();
  await page.getByLabel('任务名称', { exact: true }).fill('Prepare evidence report');
  await page.getByLabel('预期结果', { exact: true }).fill('Source-backed report');
  await page.getByLabel('验收标准', { exact: true }).fill('Three verified sources');
  await page.getByRole('button', { name: '保存任务', exact: true }).click();
  await page.getByRole('heading', { name: 'Prepare evidence report', exact: true }).waitFor();
  await page.getByRole('button', { name: '查看 / 编辑', exact: true }).click();
  await page.getByLabel('状态', { exact: true }).selectOption('finished');
  await page.getByLabel('实际结果', { exact: true }).fill('Report ready');
  await page.getByLabel('证据及其说明（链接、文件路径、对话或验证记录）', { exact: true }).fill('report.md references three sources');
  await page.getByRole('button', { name: '保存任务', exact: true }).click();
  await page.getByRole('region', { name: 'Finished', exact: true }).getByText('Report ready', { exact: true }).waitFor();
  await page.screenshot({ path: process.env.RUNNER_TEMP + '/taskboard-verified.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Browser create company, department, task, finish with evidence, and five board columns passed.');
} catch (error) {
  if (page && !page.isClosed()) console.log('Workspace screen at failure', (await page.locator('body').innerText()).slice(0, 6000));
  throw error;
} finally {
  await browser?.close();
  await engine.stop();
  await rm(home, { recursive: true, force: true });
}
