import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const require = createRequire(import.meta.url);
const upstream = await readFile(require.resolve('ds-bot/client'), 'utf8');
const entry = 'window.__ModuleLoader__.load({';
const sidebar = '    top,\n    wideContent && roster.readOnly ?';
if (upstream.split(entry).length !== 2 || upstream.split(sidebar).length !== 2) {
  throw new Error('Unexpected client wrapper or sidebar in the pinned DS Bot release.');
}
const upstreamClient = upstream.replace(entry, 'loadUpstream({')
  .replace(sidebar, '    top,\n    renderOrganisationShortcut(actions, wideContent),\n    wideContent && roster.readOnly ?');
const result = await build({
  absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
  entryPoints: ['src/client.jsx'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  loader: { '.css': 'text' },
  charset: 'utf8',
  write: false
});

// DS Bot's factory receives the same platform modules as our own factory.
// The DSH loader sees a single package, matching its single host runtime.
const lines = [
  '// Generated by scripts/build-client.mjs. Contains the DS Bot client. See third-party/.',
  'window.__ModuleLoader__.load({',
  "  id: 'bot-org-hq',",
  '  factory: (require) => {',
  '    let upstream;',
  '    const loadUpstream = ({ id, factory }) => {',
  "      if (id !== 'ds-bot') throw new Error('Unexpected upstream client ID');",
  '      upstream = factory(require);',
  '    };',
  '    function renderOrganisationShortcut(actions, wide) {',
  "      return require('react').createElement(organisation.Launcher, { wide, onOpen: () => actions.selectPanel('bot-org-hq') });",
  '    }',
  upstreamClient.trimEnd(),
  '    const module = { exports: {} };',
  result.outputFiles[0].text.trimEnd(),
  '    const organisation = module.exports;',
  '    return Object.defineProperty({',
  '      inject: [...new Set([...upstream.inject, ...organisation.inject])],',
  '      apply(ctx) { upstream.apply(ctx); organisation.apply(ctx); },',
  "    }, Symbol.toStringTag, { value: 'Module' });",
  '  },',
  '});',
  ''
];
await writeFile(new URL('../client.js', import.meta.url), lines.join('\n'));
